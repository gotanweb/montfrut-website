let catalogLanguage = detectCatalogLanguage();
const catalogStaticNodes = [];
const catalogStaticAttributes = [];
let catalogStructuredData = null;

function normalizeCatalogLanguage(locale) {
  const language = typeof locale === 'string' ? locale.toLowerCase().split('-')[0] : '';
  return language === 'es' || language === 'en' ? language : null;
}

function detectCatalogLanguage() {
  try {
    const saved = normalizeCatalogLanguage(window.localStorage.getItem('montfrut.language'));
    if (saved) return saved;
  } catch { /* Storage is optional; preserve the visitor's work in memory. */ }
  const browser = window.navigator || {};
  const languages = browser.languages && browser.languages.length ? browser.languages : [browser.language];
  for (const locale of languages) {
    const language = normalizeCatalogLanguage(locale);
    if (language) return language;
  }
  return 'en';
}

function catalogText(source, values = {}, language = catalogLanguage) {
  const key = String(source).replace(/\s+/g, ' ').trim();
  const translated = language === 'es' ? CATALOG_ES[key] ?? source : source;
  return String(translated).replace(/\{(\w+)\}/g, (match, key) => values[key] === undefined ? match : String(values[key]));
}

function localizedCatalogCopy(copy) {
  const result = {};
  for (const [key, value] of Object.entries(copy)) {
    if (typeof value === 'string') Object.defineProperty(result, key, { enumerable: true, get: () => catalogText(value) });
    else result[key] = value && typeof value === 'object' ? localizedCatalogCopy(value) : value;
  }
  return Object.freeze(result);
}

function localizedProduct(product, language = catalogLanguage) {
  const english = product.translations.en;
  const translated = product.translations[language] || {};
  return { ...product,
    name: translated.name ?? english.name,
    shortDescription: translated.shortDescription ?? english.shortDescription,
    longDescription: translated.longDescription ?? english.longDescription,
    ingredients: translated.ingredients ?? english.ingredients,
    flavorNotes: translated.flavorNotes ?? english.flavorNotes,
    category: catalogText(product.category, {}, language), flavor: catalogText(product.flavor, {}, language),
    allergyTags: product.allergyTags.map(tag => catalogText(tag, {}, language)) };
}

function variantLabel(label, language = catalogLanguage) {
  return label[language] ?? label.en;
}

// Capture only the original static DOM. Dynamic cards/controls render through the same dictionary.
// Text-node values preserve inline SVG, strong tags, form values, and all existing event handlers.
function captureCatalogStaticText() {
  const walk = node => {
    if (node.nodeType === 3) {
      if (node.nodeValue.trim()) catalogStaticNodes.push({ node, source: node.nodeValue });
      return;
    }
    if (['SCRIPT', 'STYLE', 'TEXTAREA'].includes(node.tagName)) return;
    if (node.nodeType === 1) {
      const attributes = ['aria-label', 'title', 'alt', 'placeholder'];
      if (node.tagName === 'META' && (['description', 'keywords'].includes(node.getAttribute('name')) ||
          ['og:title', 'og:description', 'twitter:title', 'twitter:description'].includes(node.getAttribute('property')))) attributes.push('content');
      for (const name of attributes) {
        if (node.hasAttribute(name)) catalogStaticAttributes.push({ node, name, source: node.getAttribute(name) });
      }
    }
    for (const child of node.childNodes || []) walk(child);
  };
  walk(document.documentElement);
  const structured = document.querySelector('script[type="application/ld+json"]');
  if (structured) {
    try { catalogStructuredData = { node: structured, data: JSON.parse(structured.textContent) }; } catch { /* Leave unrelated metadata intact. */ }
  }
}

function applyCatalogStaticText() {
  document.documentElement.lang = catalogLanguage;
  for (const { node, source } of catalogStaticNodes) {
    if (!node.isConnected) continue;
    node.nodeValue = source.replace(/\S[\s\S]*\S|\S/, text => catalogText(text.replace(/\s+/g, ' ')));
  }
  for (const { node, name, source } of catalogStaticAttributes) {
    if (node.isConnected) node.setAttribute(name, catalogText(source));
  }
  document.getElementById('catalog-language').value = catalogLanguage;
  if (catalogStructuredData) {
    const data = JSON.parse(JSON.stringify(catalogStructuredData.data));
    data.name = catalogLanguage === 'es' ? 'Catálogo de Chocolates Montfrut' : 'Montfrut Chocolate Catalog';
    data.description = catalogLanguage === 'es' ? 'Explora nuestra colección exclusiva de chocolates artesanales, bombones, trufas y cajas de regalo premium.' : 'Explore our exclusive collection of artisan chocolates, bonbons, truffles and premium gift boxes.';
    data.mainEntity.itemListElement = products.map((product, index) => {
      const view = localizedProduct(product);
      return { '@type': 'ListItem', position: index + 1, name: view.name, description: view.shortDescription };
    });
    catalogStructuredData.node.textContent = JSON.stringify(data, null, 2);
  }
}

function catalogSource(text) {
  return Object.keys(CATALOG_ES).find(key => CATALOG_ES[key] === text) || text;
}

function refreshProductLanguage() {
  if (!modalSelection) return;
  const product = localizedProduct(products.find(product => product.id === modalSelection.productId));
  document.getElementById('modal-title').textContent = product.name;
  document.getElementById('modal-description').textContent = product.longDescription;
  document.getElementById('modal-ingredients').textContent = product.ingredients;
  document.getElementById('modal-tags').innerHTML = allergyTagsHTML(product.allergyTags) +
    `<a href="#" class="modal-allergy-link" data-bs-toggle="modal" data-bs-target="#allergiesModal">${catalogText('Allergies information')}</a>`;
  document.getElementById('modal-flavor-notes').innerHTML = product.flavorNotes.map(note => `<span class="flavor-note">${note}</span>`).join('');
  document.querySelectorAll('#modal-carousel-inner img').forEach((image, index) => image.setAttribute('alt', catalogText('{name} — photo {number}', { name: product.name, number: index + 1 })));
  document.querySelectorAll('#modal-carousel-indicators button').forEach((button, index) => button.setAttribute('aria-label', catalogText('Slide {number}', { number: index + 1 })));
  document.querySelectorAll('#modal-thumbnails button').forEach((button, index) => button.setAttribute('aria-label', catalogText('Show {name} photo {number}', { name: product.name, number: index + 1 })));
  for (const { group, legend, hint, labels } of modalSelection.groups) {
    legend.textContent = `${variantLabel(group.label)} (${catalogText(group.required ? 'Required' : 'Optional')})`;
    hint.textContent = catalogText(group.selection === 'single' ? 'Choose one option.' : 'Choose one or more options.');
    if (!group.required) hint.textContent += ` ${catalogText('You may leave this group unselected.')}`;
    for (const { option, text, input } of labels) {
      const price = isOptionAvailable(option) ? ` (+${formatUsdCents(usdToCents(option.priceAdjustment))})` : '';
      text.textContent = `${variantLabel(option.label)}${price}${input.disabled ? ` — ${catalogText('Unavailable')}` : ''}`;
    }
  }
  const button = document.getElementById('modal-add-to-cart');
  document.getElementById('modal-selection-action-label').textContent = selectionEditKey ? SELECTION_COPY.save : SELECTION_COPY.add;
  button.setAttribute('aria-label', selectionEditKey ? `${SELECTION_COPY.save}: ${product.name}` : catalogText('Add {name} to selection', { name: product.name }));
  if (selectionEditKey) document.getElementById('selection-edit-note').textContent = SELECTION_COPY.editNote;
  updateModalConfiguration();
}

function setCatalogLanguage(locale, { persist = true } = {}) {
  const language = normalizeCatalogLanguage(locale);
  if (!language) return false;
  catalogLanguage = language;
  let saved = true;
  if (persist) {
    try { window.localStorage.setItem('montfrut.language', language); } catch { saved = false; }
  }
  const active = document.activeElement;
  const focusedKey = active && active.getAttribute('data-selection-key');
  const focusedAction = active && active.getAttribute('data-selection-action');
  const inquiryStatus = catalogSource(document.getElementById('inquiry-action-status').textContent);
  applyCatalogStaticText();
  const previousCarouselIndex = carouselIndex;
  renderProductGrid();
  renderSpecialCollection();
  const specialCount = products.filter(product => product.isSpecialCollection).length;
  carouselIndex = Math.min(previousCarouselIndex, Math.max(0, specialCount - getVisibleSpecialItems()));
  moveCarousel(0);
  renderMySelection();
  updateSelectionCount();
  refreshProductLanguage();
  setInquiryActionStatus(catalogText(inquiryStatus));
  document.getElementById('selection-live').textContent = '';
  const notice = getSelectionPersistenceNotice();
  if (lastToastProductId !== null) {
    const product = products.find(product => product.id === lastToastProductId);
    const name = product ? localizedProduct(product).name : String(lastToastProductId);
    document.getElementById('toast-body-text').textContent = catalogText('"{name}" added to selection.', { name }) + (notice ? ` ${notice}` : '');
  } else if (notice && selectionPersistence.noticeShown) document.getElementById('toast-body-text').textContent = notice;
  document.getElementById('catalog-language-status').textContent = saved ? '' : catalogText('Language changes apply only to this visit because saving is unavailable.');
  if (focusedKey) focusSelectionControl(focusedKey, focusedAction);
  else if (canReceiveFocus(active)) active.focus({ preventScroll: true });
  return true;
}

function initializeCatalogLanguage() {
  const selector = document.getElementById('catalog-language');
  if (selector._catalogLanguageBound) return;
  selector._catalogLanguageBound = true;
  captureCatalogStaticText();
  applyCatalogStaticText();
  selector.addEventListener('change', () => setCatalogLanguage(selector.value));
  window.addEventListener('storage', event => {
    if (event.key === 'montfrut.language') setCatalogLanguage(detectCatalogLanguage(), { persist: false });
  });
}


