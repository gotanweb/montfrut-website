// Single editable template; Node built-ins only. Run from any directory.
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, resolve } from 'node:path';
import vm from 'node:vm';

const directory = dirname(fileURLToPath(import.meta.url));
export function renderCatalog(template, productSource, translationSource, language) {
  if (!['es', 'en'].includes(language)) throw new Error('Catalog language must be es or en.');
  const context = vm.createContext({ URL, window: { location: { pathname: language === 'en' ? '/catalog/en/' : '/catalog/' } } });
  vm.runInContext(productSource, context, { timeout: 1000 });
  vm.runInContext(translationSource, context, { timeout: 1000 });
  const seo = vm.runInContext(`catalogSeo('${language}')`, context);
  const translate = text => {
    context.sourceText = text;
    return vm.runInContext(`catalogText(sourceText, {}, '${language}')`, context);
  };
  const escapeAttribute = text => text.replace(/&/g, '&amp;').replace(/"/g, '&quot;').replace(/</g, '&lt;');
  const escapeText = text => text.replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;');
  // The controlled template has quoted attributes; scripts, styles and comments stay opaque.
  let html = template.replace(/<script\b[^>]*>[\s\S]*?<\/script>|<style\b[^>]*>[\s\S]*?<\/style>|<!--[\s\S]*?-->|<[^>]+>|[^<]+/gi, token => {
    if (/^<(?:script|style)\b|^<!--/i.test(token)) return token;
    if (token.startsWith('<')) {
      const meta = /^<meta\b/i.test(token);
      return token.replace(/\b(aria-label|title|alt|placeholder|content)="([^"]*)"/g, (match, name, value) => {
        if (name === 'content' && (!meta || !/name="(?:description|keywords)"|property="(?:og|twitter):(?:title|description|image:alt)"/.test(token))) return match;
        const translated = translate(value);
        return translated === value ? match : `${name}="${escapeAttribute(translated)}"`;
      });
    }
    return token.replace(/\S[\s\S]*\S|\S/, text => {
      const translated = translate(text.replace(/\s+/g, ' '));
      return translated === text.replace(/\s+/g, ' ') ? text : escapeText(translated);
    });
  });
  const replacements = {
    // Preserve the existing relative stylesheet reference in the Spanish output.
    CATALOG_STYLES_PATH: language === 'es' ? './css/styles.css' : '/catalog/css/styles.css',
    CATALOG_LANGUAGE: language, CATALOG_URL: seo.url, CATALOG_LOCALE: seo.locale,
    OTHER_LOCALE: language === 'es' ? 'en_US' : 'es_US',
    LINKS_PATH: language === 'es' ? '/links/' : '/links/en/',
    PRIVACY_PATH: language === 'es' ? '/privacy/' : '/privacy/en/'
  };
  html = html.replace(/\{\{(\w+)\}\}/g, (match, name) => replacements[name] ?? match);
  html = html.replace(/<option value="(es|en)"([^>]*)>/g, (match, value, rest) => `<option value="${value}"${rest.replace(/ selected\b/g, '')}${value === language ? ' selected' : ''}>`);
  const json = JSON.stringify(seo.structured, null, 2).replace(/</g, '\\u003c');
  html = html.replace('<!-- CATALOG_STRUCTURED_DATA -->', `<script type="application/ld+json">\n${json}\n  </script>`);
  if (/\{\{\w+\}\}|CATALOG_STRUCTURED_DATA/.test(html)) throw new Error('Unresolved catalog template marker.');
  return '<!-- Generated by catalog/generate.mjs; edit catalog/template.html instead. -->\n' + html.replace(/\r\n/g, '\n');
}

export function generateCatalog() {
  const template = readFileSync(resolve(directory, 'template.html'), 'utf8');
  const productSource = readFileSync(resolve(directory, 'js/products.js'), 'utf8');
  const translationSource = readFileSync(resolve(directory, 'js/translations.js'), 'utf8');
  mkdirSync(resolve(directory, 'en'), { recursive: true });
  for (const language of ['es', 'en']) writeFileSync(resolve(directory, language === 'es' ? 'index.html' : 'en/index.html'), renderCatalog(template, productSource, translationSource, language));
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) generateCatalog();
